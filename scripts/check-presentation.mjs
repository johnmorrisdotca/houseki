import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { apiOf } from './api.mjs';
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.equal(pkg.name,'@johnmorrisdotca/houseki');
assert.equal(pkg.license,'MIT');
assert.equal(pkg.author,'John Morris');
assert.ok(pkg.repository.url.includes('johnmorrisdotca/houseki'));
assert.ok(pkg.homepage.includes('johnmorrisdotca.github.io/houseki'));
assert.ok(pkg.bugs.url.includes('johnmorrisdotca/houseki/issues'));
assert.ok(pkg.keywords.length>=10);
assert.ok(!pkg.dependencies||Object.keys(pkg.dependencies).length===0);
for(const path of ['README.md','LICENSE','CONTRIBUTING.md','CODE_OF_CONDUCT.md','SECURITY.md','CHANGELOG.md'])assert.ok(existsSync(path),path);
const api=apiOf();
const missing=api.flatMap(entry=>entry.exports.filter(item=>!item.doc.trim()).map(item=>`${entry.name}: ${item.name}`));
assert.deepEqual(missing,[],'Every public export needs source documentation');
assert.ok(!JSON.stringify(api).match(/(?:\/Users\/|\/home\/runner\/|[A-Z]:\\\\)/),'Public signatures must not contain machine paths');
const stylesheet=readFileSync('demo/family.css');
assert.equal(createHash('sha256').update(stylesheet).digest('hex'),'cde9cd0c66eff59cac663759f110a074dc26a0640fd4d63c7b3cc7667b1346a0');
console.log(`Presentation metadata, ${api.length} API entries, documented exports, and family stylesheet checks passed.`);
